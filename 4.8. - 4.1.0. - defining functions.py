# ключевые переменные можно объеденить

# ключевые переменные объеденяются в словарь
# # с помощью ** перед названием словаря
# **имя_словаря


# переменные указываются в таком порядке:
# аргумент(-ы), *имя_списка, **имя_словаря


def example(arg, *parg, **kwarg):
    print(f"First argument: {arg}\n\nPosition argmunts:")
    for pa in parg:
        print(f"{parg.index(pa) + 1}'s arg is {pa}")
    print(f"\nList position's argmunts: \n{parg} \n\nKeyword argmunts:")
    for kwa in kwarg:
        print(f"{kwa} : {kwarg[kwa]}")
    print(f"\nDict keyword's argmunts: \n{kwarg}\n")


# при вызове функции:
# первыми записываются обычные аргументы
# потом позиционные аргументы для списка
