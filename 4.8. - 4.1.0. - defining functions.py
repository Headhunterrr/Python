# лямбда-функция
# функция возвращающая результат одного выражения


# эквивалент лямбда-функции


# def lambda_fun(аргументы):
#     return (выражение)


# если лямбда-функция находится в return другой функции
# то при вызове возвращать она будет лямбда-функцию


# которая будет ожидать вызова и новые аргументы на вход

#               | лямбда-функция |
# (n: Any) -> (  (x: Any) -> Any  )
#   вход              выход


def exmple_with_lambda(n):
    return lambda x: x + n


print(f"{exmple_with_lambda(21)}\n")


# вызов лямбда-функции можно произвести через
# присвение функции другому имени, в данной случае f3


f3 = exmple_with_lambda(21)  # аргумент 21 присоется переменной n


# при вызове нового имени с аргументами, в данной случае f3(10)
# данные аргументы при вызове передадутся в лямбда-функцию


print(f"{f3(10)}\n")  # аргумент 10 присоется переменной x


# на выходе 31


