def f1(a, L=[]):
    print(f"Befor append() L is {type(L)}")
    L.append(a)
    print(f"After append() L is {type(L)}")
    return L


print(f1(1), '\n')  # [1]
print(f1(2), '\n')  # [1, 2]
print(f1(3), '\n')  # [1, 2, 3]

