# getter methods and setter methods - методы получения и методы настройки.

# Используя определённые декораторы, данные методы могут иметь одно имя.

# Метод получения (accessor)
# используется для получения значения атрибута, не показывая, как он хранится.
# Может также производить вычисления и преобразования значения
# перед тем, как вернёт его.

# Метод настройки (mutator)
# используется для изменения/создания новых значений атрибутов,
# а также для вывода сигнала о сохранении нового значения атрибута.


class people:
    def __init__(self, age_in):
        self.age = age_in

    @property
    def age1(self):  # getter method
        return self.age

    @age1.setter
    def age2(self, value):  # setter method
        self.age = value
        print(f"- New age is {self.age}")

# @property - декоратор, позволяющий получить доступ к методу
# без использования скобок, как к атрибуту данных
# (определяя данный метод как getter method).

# @name_getter_method.setter определяет, что происходит,
# когда присваивается значение (определяя данный метод как setter method).


jason = people(20)

