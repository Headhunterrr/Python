class Singleton():
    obj = None  # атрибут ссылающийся на экземпляр класса

    def __new__(cls, *args, **kwargs):
        if cls.obj is None:
            cls.obj = super(Singleton, cls).__new__(cls)
        return cls.obj

# Пример реализации Singleton класса, который создаёт только один экземпляр.


