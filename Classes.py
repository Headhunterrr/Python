#       - потом в родительском классе Base1 и так далее.

# Если не нашли, начинается поиск в классе Base2...
# До последнего родительского класса Base3.

# Данная структура поиска позволяет формировать линейный порядок поиска,
# чтобы предотваратить одновременный доступ к базовым классам
# (когда при поиске аргумента произвольный класс обращается однговременно
# к нескольким аргументам с одинаковым именем различных базовых классов).

