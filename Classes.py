# Генератор
# - функция, в которой используется оператор yield вместо return.

# При вызове данная функция возвращает объект генераотор.
# Его можно использовать по аналогии, как объект итератор.

# Оператор yield возвращает значения "по одному",
# сохраняя текущее состояние и значение.
# После каждой итерации ставит функцию "на паузу".

# Это послезно:
#       - если в функции есть цикл;
#       - когда объект итератор испосльзуется в цикле.


def squr(txt):
    for i in txt:
        yield i

# Пример генератора, передающего по одному символу из строки.


squr_text = squr('abcdef')
print(squr_text, '\n')

# Объект генератор с исходными данными привязываем к переменной.

for i in squr_text:
    print(i)
    if i == 'c':
        print("Stop cycle on 'c'\n")
        break

for i in squr_text:
    print(i)
    if i == 'f':
        print("Stop cycle on 'f'\n")
        break

# В рабочих программах это полезно тем,
# что сохраняется только последнее/текущее значение состояния и переменых,
# что позволяет экономить объём памяти.


def con_num(max):
    i = 1
    while i <= max:
        yield i
        i += 1

# Генератор, передающий арифметическую последовательность.


try:
    sequens_5 = con_num(5)
    while True:
        print(next(sequens_5))
except StopIteration:
    print(f"Was accepted StopIteration, sequens is was end\n")

