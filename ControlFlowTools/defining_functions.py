# лямбда функция
# функция возвращающая результат одного выражения

# def lambda_fun(аргументы):
#   return (выражение)

# эквивалент лямбда функции

def exmple_with_lambda(n):
    return lambda x: x + n

# если она находится в return другой функции
# то при вызове возвращать она будет лямбда функцию


print(exmple_with_lambda(21), '\n')
# которая будет ожидать вызова и новые аргументы
# (n: Any) -> ((x: Any) -> Any)
#   вход            выход

f3 = exmple_with_lambda(21)  # 21 -> n
print(f3(10), '\n')
# вызов лямбда функции можно произвести через
# присвение функции другому имени - f3

# при вызове нового имени с аргументами - f3(10)
# аргументы передадутся в лямбда функцию 10 -> x
# (x: Any) -> Any
#   вход     выход

# Итог
# x + n -> 10 + 21 -> 31

