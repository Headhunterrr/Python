def f1(a, L=[]):
    print(f"Befor append() L is {type(L)}")
    L.append(a)
    print(f"After append() L is {type(L)}")
    return L


print(f1(1), '\n')  # [1]
print(f1(2), '\n')  # [1, 2]
print(f1(3), '\n')  # [1, 2, 3]

# если объект аргумента изменяемый
# то он будет сохранять предыдущие изменения

# в данном случае в список добавляются новые объекты


def f2(a, L=None):
    print(f"Befor append() L is {type(L)}")
    L = []
    L.append(a)
    print(f"After append() L is {type(L)}")
    return L


print(f2(1), '\n')  # [1]
print(f2(2), '\n')  # [2]
print(f2(3), "\n")  # [3]

# если объект аргумента неизменяемый
# то при новом вызове функции объект аргумента становится таким,
