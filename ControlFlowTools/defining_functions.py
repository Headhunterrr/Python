def fib(n):         # объявили новую функцию с именем fib
    a, b = 1, 1     # получает данные на вход в переменную n
    while a < n:    # внутренние переменные записываются после имени функции
        print(a, end=' ')  # в скобках поочередно через запятую
        a, b = b, a + b
    print('\n')

# выводит числа Фибоначи до n


