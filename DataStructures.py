# A and not B or C эквивалентно (((A and (not B))  or C)

# Операторы and и or называют операторами "короткого замыкания".
# Они вычислаются "слева направо"
# и завершают оценку как только определяется результат.

# Если A, C - истины, а B - ложно,
# то в выражении A and B and C, выражение C не вычесляется,
# т.к. на выражении A and B результат уже определен.

# Результат сравнения или другое логическое выражение
# возвращает булеву переменую - False/True.

# ----------------------------------------------------------------------------

