# ----------------------------------------------------------------------------


def append_popleft_queue(list_deque, i=False):
    """App to end item or pop item from left (if i == True)."""
    if i:
        list_deque.popleft()
        print(list_deque)
        return
    list_deque.append(list_deque[-1]+1)
    print(list_deque)


append_popleft_queue(deque_list)
append_popleft_queue(deque_list, True)
append_popleft_queue(deque_list)
append_popleft_queue(deque_list, True)
print()

