# Объекты типа "последовательность",
# как правило, сравниваюстся с объектами типа "последовательность".

# Используется лексиграфический порядок,
# если первые элементы различаются, то они определяют результат сравнения.
# Если они равны, то сравнивается следующая пара элементов и т.д.

# Если все элементы последовательностей равны,
# то последовательности считаются равными.

# Если сравниваемые элементы являются последовательностями,
# то сравнение выполняется рекурсивно (действие выполняется через самого себя).

# Лексиграфический порядок для строк использует
# кодовую точку Unicode для упорядочивания отдельных символов.

# Если одна последовательность является началом другой последовательности,
# то она считается меньшей, относительно другой последовательности.

# Сравнение объектов разных типов с помощью < и >
# допустимо при наличии соответствующих методов (сравнение 0 и 0.0).

# ----------------------------------------------------------------------------

print(
    (1, 2, 3) < (1, 2, 4),
    [1, 2, 3] < [1, 2, 4],
    'ABC' < 'C' < 'Pascal' < 'Python',
    (1, 2, 3, 4) < (1, 2, 4),
    (1, 2) < (1, 2, -1),
    (1, 2, 3) == (1.0, 2.0, 3.0),
    (1, 2, ('aa', 'ab')) < (1, 2, ('abc', 'a'), 4))

