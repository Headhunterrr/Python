def example(arg,
            *parg,
            **kwarg):
    print(f"First argument arg: {arg}\n\nPosition argmunets:")
    for pa in parg:
        print(f"{parg.index(pa) + 1}'s argument is {pa}")

    print(f"\nTuple of position's argmunets: \n{parg} \n\nKeyword argmunets:")
    for kwa in kwarg:
        print(f"{kwa} : {kwarg[kwa]}")

    print(f"\nDict of keyword's argmunets: \n{kwarg}\n")

