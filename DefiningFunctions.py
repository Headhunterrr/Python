#       - под термином "аргумент" подразумевается,
#         что конкретно и какой конкретно функции было передано;
#       - под термином "параметр" подразумевается,
#         в каком качестве функция применила это принятое
#         * переменная, которая будет ссылаться на переданный ей аргумент *.

