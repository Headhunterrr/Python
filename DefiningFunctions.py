def aa():
    def aaa():
        a = 1

    def aaa1():
        nonlocal a
        a = 2

    def aaa2():
        global a
        a = 3

    a = 0
    aaa()
    print(f"enclosing a = {a}")
    aaa1()
    print(f"enclosing a = {a}")
    aaa2()
    print(f"enclosing a = {a}")


