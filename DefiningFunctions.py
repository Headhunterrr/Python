def ask_question(prompt,
                 retries=4,
                 reminder='Please try again!'):
    """Asked a question."""
    while True:
        reply = input(f"{prompt}\n\n")
        if reply in {'y', 'ye', 'yes', 'Y', 'Ye', 'Yes'}:
            print(f"\nNice!\n")
            return True

        if reply in {'n', 'no', 'nop', 'nope', 'N', 'No', 'Nop', 'Nope'}:
            print(f"\nIt's so bad, man!\n")
            return False

        retries = retries - 1
        if retries > 0:
            raise ValueError('invalid user response')
        print(reminder)

