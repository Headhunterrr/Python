def example(arg,
            *parg,
            **kwarg):
    print(f"First argument: {arg}\n\nPosition argmunts:")
    for pa in parg:
        print(f"{parg.index(pa) + 1}'s arg is {pa}")

    print(f"\nTuple of position's argmunts: \n{parg} \n\nKeyword argmunts:")
    for kwa in kwarg:
        print(f"{kwa} : {kwarg[kwa]}")

    print(f"\nDict of keyword's argmunts: \n{kwarg}\n")

