# Область видимости переменной:
#       - определяет, на коком участке кода данная переменная доступна;
#       - зависит от того, на коком участке кода данная переменная определена.

# *условно* область видимости переменной (space) - это участок кода.

# Чаще всего говорят о двух областях видимости переменных:
#       глобальной - где переменные определенны вне функции;
#       локальной - где переменные определенны внутри функции.

# *условно* простанство имён (всех объектов) (namespace)
# - участок памяти, где хранятся имена.

# Пространство имён / namespace - сопоставление имён с объектами.
# Присваивания не копируют данные, они связывают имена с объектами,
# т.е. создают новую ссылку на объект.

# Аналогично с удалением.

# Большинство пространств имён реализованы в виде словарей.

# Пространства имён создаются в разные моменты времени
# и имеют разное время жизни.

# Простраснтсво имён built-in имён создаётся при запуске интерпритатора
# и никогда не удаляется.

# Глобальное пространство имён модулей создаётся при чтении модулей.

# Глобальным пространством имён модуля с именем __main__ считается.
# Глобальное пространство имён интерпритатора.

# Локальное пространство имён для функции создаётся при вызове функции.
# Удаляется при возврате функции или выполнениии необработанного исключения.

# Точнее будет сказать забывание, т.к.
# каждый рекурсивный вызоа имеет своё собственное локальное пространство имён.

# ----------------------------------------------------------------------------

# Область видимости текстовая область программы на Python,
# где пространство имён "доступно напрямую".

# "Доступно напрямую", т.е.
# неквалифицированная ссылка на имя пытается найти имя в пространстве имён.

# ----------------------------------------------------------------------------

# При том, что область видимости определяется статически,
# используется она динамически.

# Концепция/правило LEGB, которое Python выполняет при поиске переменной.

# Если внутири функции выполняется обращение "напрямую" к переменной,
# Python ищет переменную в следующем порядке (до первого совпадения):
#   1. L (local)     - локальная (внутри функции)
#   2. E (enclosing) - локальная область объемлющих функций
#   3. G (global)    - глобальная (в скрипте/модуле/интерпритаторе)
#   4. B (bulit-in)  - встроенная (зарезервированные значения Python)

# enclosing function
# т.е. объемлющая функция - функция, внутри которой опрделенна функция.

# ----------------------------------------------------------------------------

# При объявлении переменной внутри функции
# данная переменная объявляется локально, в локальном пространстве имён,
# и отличается от глобальной переменой и переменной объемлещей функции,
# даже, если они имеют одинаковое имя.

# По сути, определяется новая переменная
# т.е. присвоение именам происходит во внутреней области видимости.

# Оператор nonlocal, объявленный внутри локальной области видимост (функции),
# объявляет переменные, из локальной области объемлющих функций.

# Оператор global объявляет переменные из глобальной области видимости
# для использования их в глобальной области видимости.

# ----------------------------------------------------------------------------

# Глобальная область видимости функции, которая определна в модуле -
# пространство имён этого модуля, независимо от того,
# с помощью какого псевдонима вызвана функция.

# ----------------------------------------------------------------------------


def aa():
    def aaa():
        a = 1

    def aaa1():
        nonlocal a
        a = 2

    def aaa2():
        global a
        a = 3

    a = 0
    aaa()
    print(f"enclosing a = {a}")
    aaa1()
    print(f"enclosing a = {a}")
    aaa2()
    print(f"enclosing a = {a}\n")


aa()
print(f"global    a = {a}\n")

