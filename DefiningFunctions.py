# Лямбда-функция
# - анонимная функция, возвращающая результат одного выражения.
# Определяется с помощью ключевого слова lambda.

# Как вложенные функции
# лямбда-функция можно ссылаться на переменные из её области видимости.

# lambda (аргументы) : выражение

# ----------------------------------------------------------------------------

# def lambda(аргумент):
#     return выражение

# Пример эквивалента лямбда-функции.

# ----------------------------------------------------------------------------


def exmple_with_lambda(n):
    return lambda x: x + n


print(exmple_with_lambda(21))
f3 = exmple_with_lambda(21)
print(f3(10))

