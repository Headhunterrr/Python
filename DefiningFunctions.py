# лямбда-функция
# анонимная функция, возвращающая результат одного выражения,
# определяющаяся с помощью ключевого слова lambda

# как вложенные функции лямбда-функция можно ссылаться на переменные
# из её области видимости

# ----------------------------------------------------------------------------

# def lambda(аргумент):
#     return выражение

# пример эквивалента лямбда-функции

# ----------------------------------------------------------------------------


def exmple_with_lambda(n):
    return lambda x: x + n


print(f"{exmple_with_lambda(21)}\n")
f3 = exmple_with_lambda(21)
print(f"{f3(10)}\n")

# пример функции, возвращающей лямбда-функцию

# ----------------------------------------------------------------------------

pairs = [(1, 'one'), (3, 'three'), (4, 'four'), (2, 'two')]
print(f"{pairs}\n")

pairs.sort(key=lambda p: p[0])
print(f"{pairs}\n")

