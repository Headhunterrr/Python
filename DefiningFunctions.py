# если при определении функции
# использовать одно имя для параметра "по умолчанию"
# и для ключевого слова в словаре

# возникнет колизия

# имя для параметра используется,
# как ключевое слово для аргумента, который передаётся этому параметру

# так как параметр может принимать аргумени только один раз,
# следующая попытка его использовать выдасть ошибку

# ----------------------------------------------------------------------------


def foo(name, **kwds):
    return 'name' in kwds


# foo(1, name = 2)

# или

# foo(1, **{'name' = 2})
# TypeError: foo() got multiple values for argument 'name'

# пример функции с колизией,
# попыткой её вызвать и ошибкой при поптке вызвать функцию

# ----------------------------------------------------------------------------

# один из вариантов исправить эту колизию
# использовать параметр, которому аргумент передаётся только с помощью позиции
# то есть использовать / при определении функции

# ----------------------------------------------------------------------------

def foo1(name, /, **kwds):
    return 'name' in kwds


print(f"{foo1(1, **{'name': 1})}\n")
print(f"{foo1(1, name=1)}\n")

# пример функции с иссправленой колизией и вызов данной функции без ошибки

