# опервтор match

# принимает выражение/объект и сравнивает его знаяение(-ия)
# с последовательными шаболонами
# представленные в виде одного или нескольких блоков case

# выполняется блок кода только первого совпавшего шаблона


def http_error(status):
    match status:
        case 400:
            return "Bad request"
        case 404:
            return "Not found"
        case 418:
            return "I'm a teapot"
        case 401 | 403 | 405:
            return "Not allowed"
        case _:
            return "Something's wrong with the internet"


print(http_error(404), '\n')

# с помощью | (символ логического "или") в одном шаблое
# можно объеденить несколько литералов и/или переменных

# _ используется, как подстановочный знак
# срабатывает всегда, когда проверяется шаблон с ним

# ------------------------------------------------------------

# шаблоны могут выглядеть как распаковка присваиваний
# (распаковка + присваивание)

