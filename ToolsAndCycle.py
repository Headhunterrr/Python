# С помощью специального атрибута данных класса __match_args__
# можно задать положение атрибутов в шаблонах.

# Сделать их позиционными (условно говоря) при вызове данного класса в шаблоне.

# Данные шаблоны эквиваленты:

#       - Point(1, var)
#       - Point(1, y=var)
#       - Point(x=1, y=var)
#       - Point(y=var, x=1)


class Point1:
    __match_args__ = ('x', 'y')

    def __init__(self, x, y):
        self.x = x
        self.y = y


x = Point1(0, 2)
points = [x, x]

match points:
    case []:
        print("No points")
    case [Point1(0, 0)]:
        print("The origin")
    case [Point1(x, y)]:
        print(f"Single point {x}, {y}")
    case [Point1(0, y1), Point1(0, y2)]:
        print(f"Two points on the Y axis at {y1}, {y2}")
    case _:
        print("Something else")
print()


