class Point:
    def __init__(self, x, y):
        self.x = x
        self.y = y


x = Point(0, 0)


def where_is(point):
    match point:
        case Point(x=0, y=0):
            print("Origin")
        case Point(x=0, y=y):
            print(f"Y = {y}")
        case Point(x=x, y=0):
            print(f"X = {x}")
        case Point():
            print("Somewhere else")
        case _:
            print("Not a point")

# в шаблоне x и y слева от знака присваивания (=) - атрибуты класса
# в шаблоне x и y справа от знака присваивания (=) - переменные шаблона


where_is(x)
