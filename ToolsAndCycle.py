# Опервтор match

# Принимает выражение и последовательно сравнивает его результат
# с шаболонами, представленные в виде одного или нескольких блоков case.

# Выполняется блок кода только первого совпавшего шаблона.


def http_error(status):
    match status:
        case 400:
            return "Bad request"
        case 404:
            return "Not found"
        case 418:
            return "I'm a teapot"
        case 401 | 403 | 405:
            return "Not allowed"
        case _:
            return "Something's wrong with the internet"


print(http_error(404), '\n')

# Символ логического "или" | в одном case объеденяет несколько шаблонов.

# Симол _ используется, как подстановочный знак,
# срабатывает всегда, когда проверяется шаблон с ним.

# ----------------------------------------------------------------------------

# Шаблоны могут выглядеть как распаковка присваиваний
# (распаковка + присваивание).

# Компоненты могут быть извлечены из выражения/объекта
# и присвоены только в переменные шаблонов.

point = (3, 'd')
match point:
    case (0, 0):
        print(f"Point in center")
    case (0, y):
        print(f"Point on Ox")
    case (x, 0):
        print(f"Point on Oy")
    case (x, y):
        print(f"Point - x = {x}, y = {y}")
    case _:
        print(f"Is not point")
print()

# Из объекта point типа кортеж
# извлечены поочерёдно 2 компоненты - 3 и 'd'.

# В четвёртом шаблоне данные компоненты,
# поочерёдно присвоенные внутренним переменным шаблона x и y.

# ----------------------------------------------------------------------------

# Если используются классы для структурирования данных,

# в шаблоне можно использовать имя класса со списком аргументов
# с возможностью сохранения значения атрибутов класса в переменные шаблона.


class Point:
    def __init__(self, x, y):
        self.x = x
        self.y = y


x = Point(0, 0)


def where_is(point):
    match point:
        case Point(x=0, y=0):
            print("Origin")
        case Point(x=0, y=y):
            print(f"Y = {y}")
        case Point(x=x, y=0):
            print(f"X = {x}")
        case Point():
            print("Somewhere else")
        case _:
            print("Not a point")


where_is(x)
print()

