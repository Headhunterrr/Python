# Основные шаблоны, которые можно использовать в case:

# Literal pattern — точное совпадение.
# Используется, когда нужно проверить конкретное значение.

# case 42:
# case "admin":
# case True:
# case None:

# Wildcard pattern — по умолчанию.
# Срабатывает, если ни один другой шаблон не подошёл.

# case _:
# case _ as value:

# Sequence pattern — структура списка или кортежа.
# Используется для сопоставления с фиксированной структурой (порядок и количество элементов).

# case [1, 2]:
# case (a, b):

# Mapping pattern — структура словаря.
# Применяется, когда нужно проверить наличие нужных ключей и их значений.

# case {"key": value}:
# case {"status": "ok", "data": content}:

# Capture pattern — захват значений.
# Позволяет сохранить значение в переменную.

# case x:
# case [code, message]:

# Class pattern — объекты и классы.
# Используется для сопоставления значений внутри объектов по их полям.

# case Point(x, y):
# case Color(r=255, g=0, b=0):
